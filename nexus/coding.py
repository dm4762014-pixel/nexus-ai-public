"""Generate task-contained source packages. Static validation never executes code."""
from __future__ import annotations
import ast
import builtins
import json
import re
import symtable
import zipfile
from html import escape
from pathlib import Path,PurePosixPath
from uuid import uuid4
from pydantic import RootModel,ConfigDict,model_validator
from .files import artifact_metadata,safe_child


class GeneratedSources(RootModel[dict[str,str]]):
    """The model may supply only a small flat mapping of paths to source text."""
    model_config=ConfigDict(strict=True)

    @model_validator(mode="after")
    def bounded(self):
        if not 1<=len(self.root)<=4:
            raise ValueError("The model may generate 1–4 source files")
        if sum(len(v) for v in self.root.values())>4000:
            raise ValueError("The model source response exceeds 4,000 characters")
        if any(not v.strip() for v in self.root.values()):
            raise ValueError("Generated source files may not be empty")
        return self


def _parse_model_sources(raw):
    raw=re.sub(r"^```(?:json)?\s*|\s*```$","",raw.strip())
    if len(raw)>12_000:
        raise ValueError("Generated JSON response exceeds its size limit")
    def unique_pairs(pairs):
        result={}
        for key,value in pairs:
            if key in result: raise ValueError("Duplicate generated file name")
            result[key]=value
        return result
    proposed=json.loads(raw,object_pairs_hook=unique_pairs)
    files=GeneratedSources.model_validate(proposed).root
    if any(Path(name).name.upper() in {"REQUEST.TXT","README.MD"} for name in files):
        raise ValueError("REQUEST.txt and README.md are generated by the trusted packager")
    files=_repair_test_imports(files)
    validation=validate_sources(files)
    if validation["unresolved_globals"]:
        raise ValueError("Generated Python contains unresolved global references")
    return files


def _undefined_globals(content,name):
    table=symtable.symtable(content,name,"exec")
    defined={s.get_name() for s in table.get_symbols() if s.is_assigned() or s.is_imported()}
    defined.update(dir(builtins))
    defined.update({"__name__","__file__","__package__","__doc__","__spec__","__builtins__","__loader__","__cached__"})
    missing=set()
    def visit(scope):
        missing.update(s.get_name() for s in scope.get_symbols() if s.is_referenced() and s.is_global() and s.get_name() not in defined)
        for child in scope.get_children(): visit(child)
    visit(table)
    return sorted(missing)


def _repair_test_imports(files):
    """Repair only missing test imports with one unambiguous local definition.

    This does not run generated source or invent dependency installation.
    Anything more complex remains an unresolved static validation error.
    """
    files=dict(files)
    exports={}
    for name,content in files.items():
        if Path(name).suffix!=".py" or len(PurePosixPath(name).parts)!=1 or Path(name).stem.startswith("test_"): continue
        for node in ast.parse(content,filename=name).body:
            if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef)):
                exports.setdefault(node.name,[]).append(Path(name).stem)
    for name,content in list(files.items()):
        if not Path(name).name.startswith("test_") or Path(name).suffix!=".py": continue
        additions=[]
        for symbol in _undefined_globals(content,name):
            modules=exports.get(symbol,[])
            if len(modules)==1: additions.append(f"from {modules[0]} import {symbol}")
        if additions:
            tree=ast.parse(content,filename=name)
            # Preserve module docstrings and __future__ import positioning.
            insert_at=0
            for index,node in enumerate(tree.body):
                if index==0 and isinstance(node,ast.Expr) and isinstance(node.value,ast.Constant) and isinstance(node.value.value,str): insert_at=node.end_lineno
                elif isinstance(node,ast.ImportFrom) and node.module=="__future__": insert_at=node.end_lineno
                else: break
            lines=content.splitlines(keepends=True)
            if insert_at and not lines[insert_at-1].endswith("\n"): lines[insert_at-1]+="\n"
            lines[insert_at:insert_at]=[line+"\n" for line in additions]
            files[name]="".join(lines)
    return files


def project_path(directory:Path,name:str)->Path:
    if not isinstance(name,str) or len(name)>160 or "\\" in name or ":" in name or name.startswith("/"): raise ValueError("Unsafe project path")
    parts=PurePosixPath(name).parts
    if not parts or any(p in {".",".."} or p.startswith(".") for p in parts): raise ValueError("Project path must remain inside workspace")
    root=Path(directory).resolve(); path=root
    for part in parts: path=safe_child(path,part)
    if not path.is_relative_to(root): raise ValueError("Project path escapes workspace")
    return path


def validate_sources(files:dict[str,str])->dict:
    if not isinstance(files,dict) or not 1<=len(files)<=12: raise ValueError("Projects require 1–12 files")
    if any(not isinstance(v,str) for v in files.values()) or sum(len(v.encode("utf-8")) for v in files.values())>200_000: raise ValueError("Source exceeds 200 KB or is not text")
    checks=[]; imports=set(); unresolved={}
    for name,content in files.items():
        project_path(Path.cwd()/"validation-only",name); suffix=Path(name).suffix.lower()
        if suffix not in {".py",".html",".css",".js",".json",".md",".txt"}: raise ValueError("Unsupported generated source format")
        if suffix==".py":
            tree=ast.parse(content,filename=name)
            # Compilation catches invalid control flow (for example return at
            # module scope) that AST parsing alone accepts. No code is run.
            compile(tree,name,"exec",dont_inherit=True,optimize=0)
            for node in ast.walk(tree):
                if isinstance(node,ast.Import): imports.update(alias.name.split(".")[0] for alias in node.names)
                elif isinstance(node,ast.ImportFrom) and node.module: imports.add(node.module.split(".")[0])
            checks.append({"file":name,"check":"Python AST syntax","passed":True})
            checks.append({"file":name,"check":"Python compilation without execution","passed":True})
            missing=_undefined_globals(content,name)
            checks.append({"file":name,"check":"Static global references","passed":not missing})
            if missing: unresolved[name]=missing
        elif suffix==".json": json.loads(content); checks.append({"file":name,"check":"JSON parse","passed":True})
        else: checks.append({"file":name,"check":"UTF-8 text recorded; build not run","passed":True})
    return {"checks":checks,"imports":sorted(imports),"unresolved_globals":unresolved,"execution_enabled":False,"build_verified":False,"reason":"Host execution is disabled. A configured disposable sandbox is required for builds or tests. Static global analysis cannot prove runtime behavior."}


def _fallback(prompt):
    if re.search(r"\b(website|web\s*page|html|landing page)\b",prompt,re.I):
        return {"index.html":'<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Project scaffold</title><link rel="stylesheet" href="style.css"><main><h1>Project scaffold</h1><p>'+escape(prompt)+'</p><label for="note">Your note</label><textarea id="note"></textarea><button id="save">Save note locally</button><p id="status" role="status"></p></main><script src="app.js"></script></html>',"style.css":'body{background:#0a1222;color:#e8f1ff;font:18px system-ui}main{max-width:760px;margin:10vh auto;padding:24px}textarea{display:block;width:95%;min-height:120px;margin:16px 0}button{background:#3478e5;color:white;padding:12px 20px;border:0;border-radius:8px}',"app.js":'document.getElementById("save").addEventListener("click",()=>{localStorage.setItem("nexus-note",document.getElementById("note").value);document.getElementById("status").textContent="Note saved in this browser.";});document.getElementById("note").value=localStorage.getItem("nexus-note")||"";'}
    return {"main.py":'"""Minimal scaffold; implement the requirements in REQUEST.txt."""\ndef main():\n    return "Scaffold created. Review REQUEST.txt before implementation."\n\nif __name__ == "__main__":\n    print(main())\n',"test_main.py":'import unittest\nfrom main import main\n\nclass ScaffoldTests(unittest.TestCase):\n    def test_main_returns_text(self):\n        self.assertIsInstance(main(),str)\n\nif __name__ == "__main__":\n    unittest.main()\n'}


def generate_project(directory:Path,prompt:str,model=None)->dict:
    if not isinstance(prompt,str) or not 3<=len(prompt)<=5000: raise ValueError("Code request must contain 3–5,000 characters")
    directory=Path(directory).resolve(); directory.mkdir(parents=True,exist_ok=True)
    warnings=[]; generation_mode="deterministic scaffold"; files=None
    if model is not None:
        try:
            raw=model.complete("Return ONLY a compact JSON object mapping relative source filenames to source strings. Example shape: {\"main.py\":\"source code\",\"test_main.py\":\"unit test code\"}. Generate at most 4 small files, 4000 source characters TOTAL. For a Python request prefer exactly main.py and test_main.py. Implement the requested behavior with standard libraries only. Keep tests short. Do not include README.md or REQUEST.txt; the packager supplies them. No shell commands, dependencies, credentials or binary files. Never claim code execution.",prompt,tokens=650)
            files=_parse_model_sources(raw); generation_mode="local model source generation"
        except Exception as exc: warnings.append(f"Model generation failed validation ({type(exc).__name__}); returned a minimal scaffold, not a completed application.")
    if files is None:
        files=_fallback(prompt); warnings.append("This package is a minimal scaffold. Requested application behavior is not verified as implemented.")
    files["REQUEST.txt"]=prompt
    files["README.md"]="# NEXUS generated source project\n\nGeneration: "+generation_mode+".\n\nReview source before running. No files were executed. Python AST syntax and JSON parsing are checked. HTML/CSS/JavaScript behavior, dependencies, builds and tests have not been verified.\n\n"+"\n".join(warnings)
    validation=validate_sources(files); identifier=uuid4().hex; source_root=directory/f"project_{identifier}"; source_root.mkdir()
    for name,content in files.items():
        target=project_path(source_root,name); target.parent.mkdir(parents=True,exist_ok=True); target.write_text(content,encoding="utf-8",newline="\n")
    archive_path=safe_child(directory,f"{identifier}.zip")
    with zipfile.ZipFile(archive_path,"w",zipfile.ZIP_DEFLATED) as archive:
        for name in files: archive.write(project_path(source_root,name),name)
    with zipfile.ZipFile(archive_path) as archive:
        if set(archive.namelist())!=set(files) or archive.testzip(): raise RuntimeError("Project archive verification failed")
        for name,content in files.items():
            if archive.read(name).decode("utf-8")!=content: raise RuntimeError("Archive source content changed")
    incomplete=generation_mode=="deterministic scaffold"
    artifact=artifact_metadata(archive_path,{"parser_reopened":True,"expected_content_present":True,"source_files":len(files),"static_validation":validation,"factual_accuracy_verified":False,"request_implementation_verified":False,"incomplete_scaffold":incomplete})
    summary=f"Created {len(files)} source files using {generation_mode}. Archive reopened and source content checked. Build and runtime tests were not run."
    if incomplete: summary="INCOMPLETE: the requested application was not generated. A minimal scaffold is available for review. "+summary
    return {**artifact,"artifact":artifact,"files":[artifact],"content":summary,"validation":validation,"warnings":warnings,"generation_mode":generation_mode,"incomplete":incomplete}
